"""Read-only SysML stubs generated from needs (D42, D64b, D81, D83). Check CK-D1.

    SYS-STH  -> part        <'SYS-STH-0001'>  sys_sth_0001       (stakeholder)
    SYS-NEED -> concern     <'SYS-NEED-0002'> sys_need_0002      (all categories, incl. problem, D81)
    SYS-REQ  -> requirement <'SYS-REQ-0012'>  sys_req_0012       frames the concerns it refines;
                carries the value fields as attributes (ears, quantity, unit, min, max, nominal, D83)

The model references requirements only through the stubs (``satisfy sys_req_0012 by x;``), so
model IDs are need IDs. Retired needs keep their stub with ``status = "retired"`` until they are
deleted (D64e). Nobody edits the stubs; ``curatrix check`` compares them with the needs.
"""
from __future__ import annotations

from curatrix import ids as idmod

PACKAGE = "NeedStubs"
VALUE_FIELDS = (("ears", "String"), ("quantity", "String"), ("unit", "String"),
                ("min", "Real"), ("max", "Real"), ("nominal", "Real"))


def name_of(nid: str) -> str:
    return nid.lower().replace("-", "_").replace(".", "_")


def _doc(text: str) -> str:
    return " ".join(str(text).split()).replace("*/", "* /")


def _lit(kind: str, v) -> str | None:
    if v in (None, ""):
        return None
    if kind == "Real":
        try:
            f = float(v)
        except (TypeError, ValueError):
            return None
        return repr(f) if f != int(f) else f"{int(f)}.0"
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(needs: dict[str, dict], package: str = PACKAGE, source: str = "needs.json") -> str:
    """The stub package for every own SYS-STH, SYS-NEED and SYS-REQ in `needs`."""
    def of(t):
        return sorted(i for i, n in needs.items() if n.get("type") == t and not n.get("is_external"))

    out = [
        f"// GENERATED by `curatrix gen stubs` from {source}. Do not edit (D42).",
        f"library package {package} {{",
        "    private import ScalarValues::*;",
        "    private import XdTrace::*;",
        "",
    ]

    def head(kw, nid, n):
        title = _doc(n.get("title", ""))
        return [f"    {kw} <'{nid}'> {name_of(nid)} {{",
                f"        doc /* {title} */",
                f'        @NeedRef {{ needId = "{nid}"; status = "{n.get("status") or "valid"}"; }}']

    for nid in of("sys-sth"):
        out += head("part", nid, needs[nid]) + ["    }"]
    for nid in of("sys-need"):
        out += head("concern", nid, needs[nid]) + ["    }"]
    for nid in of("sys-req"):
        n = needs[nid]
        out += head("requirement", nid, n)
        for field, kind in VALUE_FIELDS:
            lit = _lit(kind, n.get(field))
            if lit is not None:
                out.append(f"        attribute {field} : {kind} = {lit};")
        for parent in sorted(n.get("refines") or []):
            if idmod.kind_of(parent) == "SYS-NEED" and parent in needs:
                out.append(f"        frame {name_of(parent)};")
        out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"
